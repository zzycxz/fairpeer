func TestImageUnderstandSchema(t *testing.T) {
	u := &imageUnderstand{}
	if u.Name() != "image_understand" {
		t.Fatalf("name = %q", u.Name())
	}
	if !u.ReadOnly() {
		t.Fatal("should be read-only")
	}
	var schema map[string]any
	if err := json.Unmarshal(u.Schema(), &schema); err != nil {
		t.Fatalf("schema parse: %v", err)
	}
	props := schema["properties"].(map[string]any)
	if _, ok := props["image"]; !ok {
		t.Fatal("missing 'image' property")
	}
	if _, ok := props["prompt"]; !ok {
		t.Fatal("missing 'prompt' property")
	}
}

